def main():
    filled = 0
    skipped = 0
    
    for fid, data in FILL_DATA.items():
        filepath = f'{BASE}/{fid}.json'
        if not os.path.exists(filepath):
            print(f"  SKIP {fid}: file not found")
            skipped += 1
            continue
        
        with open(filepath, 'r', encoding='utf-8') as f:
            d = json.load(f)
        
        # Only fill if paragraphs is empty
        if d.get('paragraphs') and len(d.get('paragraphs', [])) > 0:
            print(f"  SKIP {fid}: already has content")
            skipped += 1
            continue
        
        # Update fields
        d['paragraphs'] = data.get('paragraphs', [])
        d['background'] = data.get('background', d.get('background', ''))
        d['famousQuotes'] = data.get('famousQuotes', [])
        
        if data.get('year'):
            d['year'] = data['year']
        if data.get('route_id'):
            d['route_id'] = data['route_id']
        if data.get('disputed'):
            d['disputed'] = True
            d['dispute_note'] = data.get('dispute_note', '')
        
        # Add gold_quote from famousQuotes
        if data.get('famousQuotes'):
            d['gold_quote'] = data['famousQuotes'][0]
        
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(d, f, ensure_ascii=False, indent=2)
        
        print(f"  FILL {fid}: {d['title']} ({len(d['paragraphs'])} paragraphs)")
        filled += 1
    
    # Check remaining empty entries
    remaining = []
    for f in sorted(glob.glob(f'{BASE}/*.json')):
        with open(f, 'r', encoding='utf-8') as fp:
            d = json.load(fp)
        if not d.get('paragraphs') or len(d.get('paragraphs', [])) == 0:
            remaining.append(d['id'])
    
    print(f"\n=== Summary ===")
    print(f"Filled: {filled}")
    print(f"Skipped: {skipped}")
    print(f"Remaining empty: {len(remaining)}")
    if remaining:
        print(f"Remaining IDs: {', '.join(remaining)}")

if __name__ == '__main__':
    main()
