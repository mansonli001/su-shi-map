def enhance_poem_data(poems_dir):
    """完善诗词数据"""
    enhanced_count = 0
    missing_fulltext = []
    missing_background = []
    
    for filename in sorted(os.listdir(poems_dir)):
        if not filename.endswith('.json'):
            continue
        
        filepath = os.path.join(poems_dir, filename)
        with open(filepath, 'r', encoding='utf-8') as f:
            poem = json.load(f)
        
        needs_update = False
        
        # 1. 添加作者
        if not poem.get('author') or poem['author'] == '未知':
            poem['author'] = '苏轼'
            needs_update = True
        
        # 2. 添加地点（从route_id推断）
        if not poem.get('location') or poem['location'] == '未知':
            route_id = poem.get('route_id', '')
            poem['location'] = ROUTE_LOCATIONS.get(route_id, '未知')
            needs_update = True
        
        # 3. 添加创作背景
        poem_id = filename.replace('.json', '')
        if not poem.get('background') or poem['background'] == '':
            if poem_id in POEM_BACKGROUNDS:
                poem['background'] = POEM_BACKGROUNDS[poem_id]
                needs_update = True
            else:
                missing_background.append(poem_id)
        
        # 4. 添加全文
        if not poem.get('fullText') and not poem.get('paragraphs'):
            if poem_id in POEM_FULL_TEXTS:
                poem['fullText'] = POEM_FULL_TEXTS[poem_id]
                needs_update = True
            else:
                missing_fulltext.append(poem_id)
        
        # 5. 添加 has_full_text 标记
        has_full = bool(poem.get('fullText') or poem.get('paragraphs'))
        if poem.get('has_full_text') != has_full:
            poem['has_full_text'] = has_full
            needs_update = True
        
        # 保存更新
        if needs_update:
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump(poem, f, ensure_ascii=False, indent=2)
            enhanced_count += 1
            print(f"✓ 已完善: {poem_id} - {poem['title']}")
    
    print(f"\n完善完成！共处理 {enhanced_count} 首诗词")
    
    if missing_fulltext:
        print(f"\n缺少全文的诗词 ({len(missing_fulltext)}首):")
        for pid in missing_fulltext:
            print(f"  - {pid}")
    
    if missing_background:
        print(f"\n缺少创作背景的诗词 ({len(missing_background)}首):")
        for pid in missing_background:
            print(f"  - {pid}")
    
    return {
        'enhanced_count': enhanced_count,
        'missing_fulltext': missing_fulltext,
        'missing_background': missing_background
    }

