updated = 0
skipped = 0
for pid, (lat, lng, note) in CORRECTIONS.items():
    pf = os.path.join(PLACES_DIR, f'{pid}.json')
    if not os.path.exists(pf):
        skipped += 1
        continue
    with open(pf, encoding='utf-8') as f:
        pd = json.load(f)
    
    old_lat, old_lng = pd.get('lat', 0), pd.get('lng', 0)
    
    # 检查是否已经是正确坐标
    d = 0
    if old_lat and old_lng:
        R = 6371000
        p1, p2 = math.radians(old_lat), math.radians(lat)
        dp = math.radians(lat-old_lat)
        dl = math.radians(lng-old_lng)
        a = math.sin(dp/2)**2 + math.cos(p1)*math.cos(p2)*math.sin(dl/2)**2
        d = 2*R*math.asin(math.sqrt(a))
    
    if d < 50:  # 已是正确坐标
        skipped += 1
        continue
    
    pd['lat'] = lat
    pd['lng'] = lng
    pd['coordinate_source'] = 'manual_corrected'
    
    with open(pf, 'w', encoding='utf-8') as f:
        json.dump(pd, f, ensure_ascii=False, indent=2)
    
    pub_pf = os.path.join(PUBLIC_DIR, f'{pid}.json')
    with open(pub_pf, 'w', encoding='utf-8') as f:
        json.dump(pd, f, ensure_ascii=False, indent=2)
    
    updated += 1
    an = pd.get('ancient_name', '')
    print(f"  OK {pid} {an}: 偏差{d:.0f}m → 修正 [{note}]")

print(f"\n共修正 {updated} 个地点，跳过 {skipped} 个（已正确或不存在）")
