with open('data-v4/places-index.json') as f:
    pi = json.load(f)

issues = []

for p in pi['places']:
    pid = p['id']
    pf = f'data-v4/places/{pid}.json'
    if not os.path.exists(pf):
        continue
    with open(pf) as f:
        pd = json.load(f)
    
    an = pd.get('ancient_name', '')
    mv = pd.get('modern_visit', {})
    if not mv or not mv.get('cityname'):
        continue
    
    # 从地点名推断省份
    place_province = None
    for key, prov in PLACE_PROVINCE.items():
        if key in an:
            place_province = prov
            break
    
    if not place_province:
        continue
    
    # 从POI城市推断省份
    poi_city = mv.get('cityname', '')
    poi_province = None
    for city, prov in CITY_PROVINCE.items():
        if city in poi_city or poi_city in city:
            poi_province = prov
            break
    
    if not poi_province:
        continue
    
    # 比较省份
    if place_province != poi_province:
        issues.append({
            'id': pid,
            'name': an,
            'place_province': place_province,
            'poi_city': poi_city,
            'poi_province': poi_province,
            'lat': pd.get('lat', 0),
            'lng': pd.get('lng', 0),
            'poi_name': mv.get('amap_name', ''),
        })

issues.sort(key=lambda x: x['name'])

print(f'POI城市与地点省份不匹配的地点: {len(issues)}个')
print()
