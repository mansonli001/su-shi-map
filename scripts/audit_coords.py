with open('data-v4/places-index.json') as f:
    pi = json.load(f)

issues = []
for p in pi['places']:
    pid = p['id']
    an = p.get('ancient_name', '')
    lat = p.get('lat', 0)
    lng = p.get('lng', 0)
    
    if lat == 0 or lng == 0:
        issues.append((pid, an, lat, lng, '坐标为0'))
        continue
    
    # 检查是否在中国范围内
    if lat < 18 or lat > 54 or lng < 73 or lng > 136:
        issues.append((pid, an, lat, lng, '坐标超出中国范围'))
        continue
    
    # 根据地点名推断省份，检查坐标是否在省份范围内
    province = None
    for key, prov in PLACE_PROVINCE.items():
        if key in an:
            province = prov
            break
    
    if province and province in PROVINCE_RANGES:
        min_lat, max_lat, min_lng, max_lng = PROVINCE_RANGES[province]
        if not (min_lat <= lat <= max_lat and min_lng <= lng <= max_lng):
            issues.append((pid, an, lat, lng, f'坐标不在{province}范围内({min_lat}-{max_lat}N, {min_lng}-{max_lng}E)'))

print(f'坐标与名称不匹配的问题: {len(issues)}个')
for pid, an, lat, lng, desc in issues:
    print(f'  {pid} {an}: ({lat},{lng}) - {desc}')
