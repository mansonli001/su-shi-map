def extract_excerpt_v4(body: str, place_name: str) -> str:
    """精确 excerpt 提取：必须是原文原话"""
    lines = body.split('\n')
    content = []
    for line in lines:
        line = line.strip()
        if not line:
            continue
        if line.startswith('原创') or '有生余年' in line:
            continue
        if re.match(r'^\d{4}-\d{2}-\d{2}', line):
            continue
        content.append(line)

    full_text = '\n'.join(content)
    sentences = re.split(r'(?<=[。！？])', full_text)
    sentences = [s.strip() for s in sentences if s.strip() and len(s.strip()) >= 15]

    def score(s):
        sc = 0
        if '我' in s:
            sc += 3
        feeling = ['觉得', '爱死', '简直', '多么', '震撼', '远超', '难忘',
                   '不想走', '想住', '想留', '一生', '永远', '太美', '真好',
                   '治愈', '温暖', '孤独', '寂寞', '矫情', '羞愧',
                   '爱', '喜欢', '感动', '美', '绝', '牛', '棒']
        for w in feeling:
            if w in s:
                sc += 2
        visual = ['阳光', '月光', '海风', '落日', '晚霞', '星空',
                  '溪流', '山', '水', '花', '树', '雨', '雪', '海']
        for w in visual:
            if w in s:
                sc += 1
        if 30 <= len(s) <= 100:
            sc += 2
        elif 20 <= len(s) <= 120:
            sc += 1
        if re.search(r'\d+元|\d+块|门票|开放时间|攻略|交通|路线|住宿推荐', s):
            sc -= 5
        if len(s) > 150:
            sc -= 2
        # 含地点名加分
        if place_name and place_name in s:
            sc += 2
        return sc

    scored = [(score(s), s) for s in sentences]
    scored.sort(key=lambda x: -x[0])

    if scored and scored[0][0] >= 3:
        excerpt = scored[0][1]
        if len(excerpt) > 150:
            excerpt = excerpt[:147] + '…'
        return excerpt

    for s in sentences:
        if '我' in s and len(s) <= 150:
            return s

    return ''


def extract_snacks_v4(body: str) -> list:
    """精确食物提取"""
    snacks = []
    patterns = [
        r'吃了[一]?[个份碗盘碟]?([\u4e00-\u9fff]{2,6}(?:汤|面|粉|饼|糕|包|饺|肉|鱼|虾|蟹|鹅|鸡|鸭|串|丸|粥|饭|羹|卷|酥|冻|馍|豆腐|豆花|奶茶))',
        r'喝了[一]?[个份碗杯]?([\u4e00-\u9fff]{2,6}(?:汤|茶|酒|汁|奶茶))',
        r'要了[一]?[个份碗盘碟]?([\u4e00-\u9fff]{2,6}(?:汤|面|粉|饼|糕|包|饺|肉|鱼|虾|蟹|鹅|鸡|鸭|串|丸|粥|饭|羹|卷|酥|冻|馍|豆腐|豆花|奶茶|茶|酒))',
        r'点了[一]?[个份碗盘碟]?([\u4e00-\u9fff]{2,6}(?:汤|面|粉|饼|糕|包|饺|肉|鱼|虾|蟹|鹅|鸡|鸭|串|丸|粥|饭|羹|卷|酥|冻|馍|豆腐|豆花|奶茶|茶|酒))',
        r'买了[一]?[个份碗]?([\u4e00-\u9fff]{2,6}(?:汤|面|粉|饼|糕|包|饺|肉|鱼|虾|蟹|鹅|鸡|鸭|串|丸|粥|饭|羹|卷|酥|冻|馍|豆腐|豆花|奶茶|茶|酒))',
        r'([\u4e00-\u9fff]{2,4}火烧)',
        r'([\u4e00-\u9fff]{2,4}火锅)',
        r'([\u4e00-\u9fff]{2,4}米线)',
        r'([\u4e00-\u9fff]{2,4}奶茶)',
        r'([\u4e00-\u9fff]{2,4}烧烤)',
        r'([\u4e00-\u9fff]{2,4}烤鱼)',
        r'([\u4e00-\u9fff]{2,4}串串)',
        r'([\u4e00-\u9fff]{2,4}螺蛳粉)',
    ]

    exclude = {'东西', '午饭', '晚饭', '早餐', '早饭', '晚餐', '午餐',
               '点心', '零食', '美食', '饭菜', '很多酒', '点啤酒',
               '这么多酒', '一顿羊肉', '一顿椰子鸡', '一顿饭',
               '一个肋板火烧', '一个板肠火烧',
               '便饭', '顿午饭', '顿晚饭', '顿饭', '顿早餐',
               '堆的水果面包', '点当地的白酒', '两瓶啤酒', '两瓶柠檬茶',
               '们在用柴火锅', '馄饨和俩包', '啤酒',
               }

    for pattern in patterns:
        matches = re.findall(pattern, body)
        for m in matches:
            m = re.sub(r'^[一个份碗盘碟瓶杯壶两几]', '', m)
            m = re.sub(r'^[顿堆些]', '', m)
            m = m.replace('的', '')
            if m not in exclude and 2 <= len(m) <= 8:
                snacks.append(m)

    seen = set()
    result = []
    for s in snacks:
        if s not in seen:
            seen.add(s)
            result.append(s)

    return result[:5]


def assign_trip_tag(date: str, title: str) -> str:
    """分配 trip_tag"""
    if '北上之旅' in title:
        return '2024北上之旅'
    if '带老爸' in title or '带老爹' in title or '带倔强' in title:
        return '2025-2026带父南下'
    if '南下' in title:
        return '2022南下之旅'

    if '2022-08' <= date <= '2022-12':
        return '2022南下之旅'
    if '2023-06' <= date <= '2023-07':
        return '2023东北自驾'
    if '2023-08' <= date <= '2023-09':
        return '2023西北自驾'
    if '2024-07' <= date <= '2024-08':
        return '2024北上之旅'
    if '2025-01' <= date <= '2025-02':
        return '2025春节西藏'
    if '2025-08' <= date <= '2025-09':
        return '2025云南之旅'
    if '2025-12' <= date or '2026-01' <= date <= '2026-06':
        return '2025-2026带父南下'

    return ''


def main():
    files = []
    with open(TRAVEL_LIST, 'r') as f:
        for line in f:
            line = line.strip()
            if line and Path(line).exists():
                files.append(line)

    print(f"加载 {len(files)} 篇旅行文章")

    # 按具体地点分组
    # 策略：每篇文章可能匹配到多个地点（从 PLACE_MAP），每个地点独立记录
    # 同时，如果一篇文章没匹配到任何 PLACE_MAP 地点，用 region 兜底
    place_groups = defaultdict(list)
    unmatched_count = 0

    for f in files:
        try:
            with open(f, 'r', encoding='utf-8') as fh:
                data = json.load(fh)
        except:
            continue

        title = data.get('title', '')
        date = data.get('date', '')
        region = data.get('region', '')
        body = data.get('body', '')

        if date < '2022-01-01':
            continue

        # 排除海外
        is_overseas = False
        for kw in OVERSEAS_KEYWORDS:
            if kw in title or kw in body[:500]:
                is_overseas = True
                break
        if is_overseas:
            continue

        # 从文章中提取所有匹配的地点
        places = match_places(title, body, region)
        if not places:
            unmatched_count += 1
            continue

        excerpt = extract_excerpt_v4(body, '')
        snacks = extract_snacks_v4(body)
        trip_tag = assign_trip_tag(date, title)

        for place in places:
            key = f"{place['province']}_{place['place_name']}"
            place_groups[key].append({
                **place,
                'region': region,
                'visit_date': f"{date[:4]}年{int(date[5:7])}月" if date else '',
                'source_date': date,
                'trip_tag': trip_tag,
                'excerpt': excerpt,
                'snacks': snacks,
                'source_title': title,
            })

    print(f"未匹配地点的文章数: {unmatched_count}")

    # 合并同一地点
    rows = []
    counter = 1

    for key, articles in sorted(place_groups.items()):
        # 选 excerpt 质量最好的
        best = max(articles, key=lambda a: len(a.get('excerpt', '')))

        # 合并 snacks
        all_snacks = []
        seen = set()
        for a in articles:
            for s in a.get('snacks', []):
                if s not in seen:
                    seen.add(s)
                    all_snacks.append(s)

        # 合并 trip_tag（取第一个非空的）
        trip_tag = ''
        for a in articles:
            if a.get('trip_tag'):
                trip_tag = a['trip_tag']
                break

        # 合并 visit_dates（保留所有访问日期）
        dates = sorted(set(a['source_date'] for a in articles if a.get('source_date')))
        visit_date_str = best['visit_date']

        # 构建多次访问历史
        visit_history = []
        for d in dates:
            year = d[:4]
            month = int(d[5:7])
            tag = ''
            for a in articles:
                if a.get('source_date') == d and a.get('trip_tag'):
                    tag = a['trip_tag']
                    break
            visit_history.append(f"{year}年{month}月{'（' + tag + '）' if tag else ''}")

        if len(visit_history) > 1:
            visit_date_str = visit_history[0]
            # 多次访问信息放在 excerpt 前面
            multi_visit = f"多次到访：{'、'.join(visit_history)}。"
            if best.get('excerpt'):
                excerpt_final = multi_visit + best['excerpt']
            else:
                excerpt_final = multi_visit
        else:
            excerpt_final = best.get('excerpt', '')

        # 判断是否 featured
        featured = len(articles) >= 2 or len(best.get('excerpt', '')) >= 50

        row = {
            'id': f'HY{counter:03d}',
            'province': best['province'],
            'city': best['city'],
            'place_name': best['place_name'],
            'full_name': f"{best['province']}·{best['place_name']}",
            'region': best.get('region', ''),
            'visit_date': visit_date_str,
            'trip_tag': trip_tag,
            'excerpt': excerpt_final[:300],  # 允许更长，因为含多次访问历史
            'snacks': json.dumps(all_snacks[:5], ensure_ascii=False),
            'search_term': best['search_term'],
            'lat': '',
            'lng': '',
            'image_url': '',
            'article_url': '',
            'featured': str(featured).lower(),
            'source_title': best['source_title'],
            'article_count': len(articles),
            'visit_count': len(dates),
            'visit_history': json.dumps(visit_history, ensure_ascii=False),
            'human_reviewed': 'N',
        }
        rows.append(row)
        counter += 1

    # 写入 CSV
    CSV_FIELDS = [
        "id", "province", "city", "place_name", "full_name", "region",
        "visit_date", "trip_tag", "excerpt", "snacks", "search_term",
        "lat", "lng", "image_url", "article_url", "featured",
        "source_title", "article_count", "visit_count", "visit_history", "human_reviewed",
    ]

    out_path = '/tmp/heye-prompts/heye_locations_v4.csv'
    with open(out_path, 'w', newline='', encoding='utf-8-sig') as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS, extrasaction='ignore')
        writer.writeheader()
        writer.writerows(rows)

    # 统计
    provinces = set(r['province'] for r in rows)
    tags = defaultdict(int)
    for r in rows:
        if r['trip_tag']:
            tags[r['trip_tag']] += 1
        else:
            tags['无标签'] += 1
    empty_exc = sum(1 for r in rows if not r.get('excerpt', '').strip())
    empty_snacks = sum(1 for r in rows if r.get('snacks', '[]') == '[]')
    featured_count = sum(1 for r in rows if r['featured'] == 'true')
    multi_visit = sum(1 for r in rows if r.get('visit_count', 1) > 1)

    print(f"\nv4 精提取完成！")
    print(f"   地点数: {len(rows)}")
    print(f"   覆盖省份: {len(provinces)}")
    print(f"   精选地点: {featured_count}")
    print(f"   多次到访: {multi_visit}")
    print(f"   空 excerpt: {empty_exc}/{len(rows)}")
    print(f"   空 snacks: {empty_snacks}/{len(rows)}")
    print(f"\n   出行标签:")
    for t in sorted(tags.keys()):
        print(f"     {t}: {tags[t]} 个地点")
    print(f"\n   输出: {out_path}")

    # 输出前15个地点供检查
    print(f"\n=== 前15个地点抽检 ===")
    for r in rows[:15]:
        exc = r['excerpt'][:80]
        print(f"  {r['full_name']:20s} | {exc}...")
        print(f"  {'':20s} | snacks: {r['snacks'][:40]} | visits: {r['visit_count']}")


if __name__ == '__main__':
    main()
