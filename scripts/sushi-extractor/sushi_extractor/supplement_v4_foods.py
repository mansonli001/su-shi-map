def get_foods_for_place(ancient_name, modern_name):
    """获取地点的美食"""
    # 精确匹配
    if ancient_name in FOOD_DATA:
        return FOOD_DATA[ancient_name]
    
    # 部分匹配
    for key in FOOD_DATA:
        if key in ancient_name or ancient_name in key:
            return FOOD_DATA[key]
    
    # 从modern_name提取省份
    for province, foods in PROVINCE_FOODS.items():
        if province in modern_name:
            return foods
    
    return []

def supplement_v4():
    files = sorted([f for f in os.listdir(V4_DIR) if f.endswith('.json')])
    
    total = len(files)
    updated = 0
    foods_added = 0
    
    for filename in files:
        path = os.path.join(V4_DIR, filename)
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        ancient_name = data.get('ancient_name', '')
        modern_name = data.get('modern_name', '')
        
        # 补充美食
        if 'foods' not in data or not data['foods'] or len(data['foods']) == 0:
            foods = get_foods_for_place(ancient_name, modern_name)
            if foods:
                data['foods'] = foods
                foods_added += 1
                updated += 1
        
        # 保存
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    
    print("="*60)
    print("v4地点美食补充完成")
    print("="*60)
    print(f"总地点数: {total}")
    print(f"补充美食: {foods_added} 个")
    print(f"更新文件: {updated} 个")
    
    # 验证
    foods_count = 0
    for filename in files:
        path = os.path.join(V4_DIR, filename)
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        if data.get('foods'):
            foods_count += 1
    
    print(f"\n验证 - 有美食的地点: {foods_count}/{total}")

if __name__ == "__main__":
    supplement_v4()
